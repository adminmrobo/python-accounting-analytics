import re as _re
def lint(code, where=""):
    """코드 규칙 검사: 들여쓰기 없음 · def 없음 · for 없음 (문자열·주석 안은 보지 않는다)."""
    bad = []
    body = _re.sub(r'("""|\'\'\')[\s\S]*?\1', lambda m: "\n" * m.group().count("\n"), code)   # 여러 줄 문자열 비우기
    for no, line in enumerate(body.splitlines(), 1):
        src = _re.sub(r'"[^"\n]*"|\'[^\'\n]*\'', '""', line).split("#")[0]
        if line[:1] in (" ", "\t") and line.strip():
            bad.append((no, "들여쓰기", line))
        if _re.search(r"\b(def|for|while|lambda|class)\b", src):
            bad.append((no, "def/for", line))
        if _re.match(r"\s*(if|else|elif|try|except|with)\b.*:\s*$", src):
            bad.append((no, "블록", line))
    assert not bad, f"{where}: 코드 규칙 위반 {bad[:5]}"

